import assert from 'node:assert/strict';
import { createDemoBackend } from '../src/lib/backend/demo.ts';
import { dayRows, indexBoard, summarize } from '../src/lib/status.ts';

const backend = createDemoBackend();
assert.equal(typeof backend.saveWeekendTerm, 'function', '주말 기간 생성 API가 있어야 한다');
await backend.signIn('teacher', 'demo');
const old = (await backend.loadTeacherData())!;
const original = JSON.stringify(old);
const termId = await backend.saveWeekendTerm(old.klass.id, {
  termId: null, name: '기말고사 주말 자율 참여', deadlineMinutes: 540, instructions: '',
});
await backend.setTermParticipants(termId, ['s01', 's02']);
await backend.setPublicTerm(old.klass.id, termId);
backend.demo.setClock('weekend-sunday');
let info = await backend.publicInfo();
assert.deepEqual(info.open_days, []);
assert.equal(info.next_day?.record_date, '2026-11-14');
const input = (date: string) => ({ studentNo: '10901', recordDate: date, requestId: crypto.randomUUID(), token: null,
  images: [{ blob: new Blob(['photo'], { type: 'image/webp' }), mime: 'image/webp' }], selfMinutes: 120, note: null });
await assert.rejects(backend.publicSubmit(input('2026-11-14')), /window_not_open/);
backend.demo.setClock('weekend-before');
info = await backend.publicInfo();
assert.deepEqual(info.open_days.map(d => d.record_date), ['2026-11-15', '2026-11-14']);
await assert.rejects(backend.publicSubmit({ ...input('2026-11-14'), studentNo: '10903' }), /not_participant/);
const saturday = input('2026-11-14');
await backend.setPublicTerm(old.klass.id, null);
await assert.rejects(backend.publicSubmit({ ...saturday, termId }), /term_changed/);
await backend.setPublicTerm(old.klass.id, termId);
backend.demo.setFailure('confirm_lost');
await assert.rejects(backend.publicSubmit(saturday), /network/);
const recovered = await backend.publicSubmit(saturday);
const recoveredWithoutPhotos = await backend.publicRecover({ ...saturday, termId });
assert.equal(recoveredWithoutPhotos?.version, 1);
assert.equal(await backend.publicRecover({ ...input('2026-11-15'), termId }), null);
assert.equal(recovered.replayed, true);
assert.equal(recovered.version, 1);
assert.equal(recovered.late, false);
assert.equal(recovered.deadline_at, '2026-11-16T00:00:00.000Z');
await assert.rejects(backend.publicSubmit({ ...saturday, recordDate: '2026-11-15' }), /bad_request/);
await assert.rejects(backend.publicSubmit({ ...saturday, studentNo: '10902' }), /bad_request/);
backend.demo.setClock('weekend-after');
const sunday = await backend.publicSubmit(input('2026-11-15'));
assert.equal(sunday.late, true);
let current = (await backend.loadTeacherData(termId))!;
assert.equal(current.days.length, 8);
assert.equal(current.submissions.length, 2);
assert.deepEqual(current.submissions.map(s => s.record_date), ['2026-11-14', '2026-11-15']);
await backend.saveWeekendTerm(old.klass.id, { termId, name: '기말고사 주말', deadlineMinutes: 600, instructions: '' });
current = (await backend.loadTeacherData(termId))!;
assert.equal(current.days[0].deadline_at, recovered.deadline_at, '열린 주말 마감 보존');
assert.equal(current.days[2].deadline_at, '2026-11-23T01:00:00.000Z');
const board = indexBoard(current.submissions, current.exemptions, current.excuses, current.participantIds);
const rows = dayRows(current.days[0], current.students, board, await backend.serverNow());
assert.equal(summarize(rows, current.days[0]).target, 2);
assert.equal(rows.find(r => r.student.student_no === '10903')?.state, 'not_target');
await backend.setTermParticipants(termId, ['s02']);
await assert.rejects(backend.publicSubmit(saturday), /not_participant/);
const legacy = (await backend.loadTeacherData(old.term!.id))!;
assert.equal(JSON.stringify({ ...legacy, klass: old.klass, terms: old.terms }), original, '기존 기간/학생/제출 보존');
backend.demo.setClock('weekend-ended');
info = await backend.publicInfo();
assert.deepEqual(info.open_days, []);
assert.equal(info.next_day, null);
assert.equal(info.term?.submission_mode, 'weekend', '종료 후 예전 일일 기간으로 돌아가지 않음');
console.log('PASS: 주말 데모 일정, 신청자, 날짜 바인딩, 응답 유실 복구, 마감 보존, 통계, 기존 데이터 보존, 운영 종료');
